constexpr std::string_view surface_material_name(std::uint8_t id) noexcept {return id<surface_material_names.size()?surface_material_names[id]:"Unknown";}
// Portable replay dataset v1 uses its OWN name-based codes (export_native_dataset.py).
// This conversion preserves that historical format; unknown/unrepresented names map to 255.
constexpr std::uint8_t dataset_material_code(std::uint8_t physical_id) noexcept {
    switch(static_cast<SurfaceMaterialId>(physical_id)){
    case SurfaceMaterialId::Asphalt:return 1;
    case SurfaceMaterialId::Concrete:return 2;
    case SurfaceMaterialId::Dirt:return 3;
    case SurfaceMaterialId::Grass:return 4;
    case SurfaceMaterialId::Ice:return 5;
    case SurfaceMaterialId::Metal:return 6;
    case SurfaceMaterialId::Plastic:return 7;
    case SurfaceMaterialId::Rubber:return 8;
    case SurfaceMaterialId::Sand:return 9;
    case SurfaceMaterialId::Wood:return 10;
    case SurfaceMaterialId::Water:return 11;
    default:return 255;
    }
}
